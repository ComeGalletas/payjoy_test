<?php

declare(strict_types=1);

namespace FxInstallments\Db;

use RuntimeException;

/**
 * The generated api/db/schema.sql: the full schema after every migration, for reading. It is
 * never applied; Migrator is the only way the schema reaches a database.
 *
 * dump() runs the migration list on an in-memory SQLite database and reads back each table and
 * index definition, so the file can't drift from the migrations (SchemaDumpTest compares the
 * two). Tables are sorted by name, each followed by its indexes.
 */
final class Schema
{
    public static function path(): string
    {
        return dirname(__DIR__, 2) . '/db/schema.sql';
    }

    public static function dump(): string
    {
        $pdo = Database::connect('sqlite::memory:');
        $migrator = new Migrator($pdo);
        $migrator->migrate();

        $rows = $pdo->query(
            "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'",
        )->fetchAll();

        $tables = [];
        $indexes = [];
        foreach ($rows as $row) {
            // A table renamed by a rebuild (events_new -> events) is stored as CREATE TABLE "events".
            $sql = (string) preg_replace('/^CREATE TABLE "([a-z_]+)"/', 'CREATE TABLE $1', (string) $row['sql']);
            if ($row['type'] === 'table') {
                $tables[(string) $row['name']] = $sql;
            } elseif ($row['type'] === 'index') {
                $indexes[(string) $row['tbl_name']][(string) $row['name']] = $sql;
            } else {
                throw new RuntimeException('Unexpected schema object type: ' . $row['type']);
            }
        }
        ksort($tables);

        $out = [
            sprintf('-- FX Installments schema, version %d (docs/PLAN.md §5).', $migrator->latestVersion()),
            '--',
            '-- GENERATED by `php api/bin/migrate.php --dump` from api/src/Db/Migrations.php. Do not edit:',
            '-- add a migration and regenerate. SchemaDumpTest fails when this file and the migrations differ.',
            '-- Databases are created and upgraded only by `php api/bin/migrate.php`, never from this file.',
            '-- schema_version is recorded in app_state.',
            '',
        ];
        foreach ($tables as $name => $sql) {
            $out[] = $sql . ';';
            $tableIndexes = $indexes[$name] ?? [];
            ksort($tableIndexes);
            foreach ($tableIndexes as $indexSql) {
                $out[] = $indexSql . ';';
            }
            $out[] = '';
        }

        return implode("\n", $out);
    }

    /**
     * Writes dump() to api/db/schema.sql (UTF-8, LF, no BOM).
     */
    public static function write(): string
    {
        $path = self::path();
        if (file_put_contents($path, self::dump()) === false) {
            throw new RuntimeException('Could not write db/schema.sql');
        }

        return $path;
    }
}
